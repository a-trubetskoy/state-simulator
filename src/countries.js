// Flag artwork, keyed by the same code: real SVGs (flag-icons), not the
// Unicode flag emoji, because Windows' emoji font doesn't draw those — it
// falls back to plain two-letter text, defeating the point of a flag icon.
// import.meta.glob resolves every file in the package's flag set at build
// time to its bundled asset URL; only the ones a menu actually renders are
// ever fetched.
const FLAG_FILES = import.meta.glob("/node_modules/flag-icons/flags/4x3/*.svg", {
  eager: true,
  import: "default",
});
export const FLAG_URL = Object.fromEntries(
  Object.entries(FLAG_FILES).map(([path, url]) => [path.slice(-6, -4).toUpperCase(), url])
);

